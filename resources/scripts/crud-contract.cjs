const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const roots = ['src/js/crud', 'src/js/Pages/crud']
function crudFingerprint() {
  const hash = crypto.createHash('sha256')
  for (const root of roots) {
    const dir = path.join(__dirname, '..', root)
    for (const name of fs.readdirSync(dir).sort()) {
      if (/\.(test|spec)\./.test(name)) continue
      hash.update(root + '/' + name + '\0')
      hash.update(fs.readFileSync(path.join(dir, name)))
      hash.update('\0')
    }
  }
  return 'sha256:' + hash.digest('hex')
}
module.exports = { crudFingerprint }
if (require.main === module) {
  const destination = path.join(__dirname, '../../features/crud/client_generated.go')
  fs.writeFileSync(destination, '// Code generated by resources/scripts/crud-contract.cjs. DO NOT EDIT.\n\npackage crud\n\n//go:generate node ../../resources/scripts/crud-contract.cjs\n\n// ClientFingerprint identifies the embedded CRUD renderer.\nconst ClientFingerprint = ' + JSON.stringify(crudFingerprint()) + '\n')
}
